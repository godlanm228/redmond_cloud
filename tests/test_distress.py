"""Распознавание острой ситуации.

Положительные примеры — формулировки, которыми владелец реально описывал такие
моменты, и типовые экстренные фразы. Отрицательные — его настоящие сообщения
из боевой базы за 15.08–14.09.2026: на них бот НЕ должен переходить в режим
«что случилось?».
"""

import pytest

from logic import distress


@pytest.mark.parametrize("text", [
    "Суисайд",                                   # 04.09.2026, дословно
    "мне плохо",
    "мне очень плохо, еду в больницу",
    "дико болит живот",
    "адская боль в животе",
    "вызвал скорую",
    "не могу дышать",
    "я в больнице",
    "bin im Krankenhaus",
])
def test_acute_signals_are_detected(text):
    assert distress.detect(text), text


@pytest.mark.parametrize("text", [
    # настоящие сообщения владельца из базы
    "Работаю",
    "Мут на 7 дней",
    "Курю кальян с Настей Чилю Ничего не планирую кроме чила Потом в доту пойду",
    "Покажи последние 10 записей",
    "А какой обед? Ты шайбанутый 20.30 на улице.",
    "Не позанимался еще, это план на тудей Креатин пью с молоком",
    # похожие, но не острые
    "плохо спал",
    "болит голова немного",
    "умираю со смеху",
    "помоги с кодом",
])
def test_ordinary_messages_are_not_acute(text):
    assert not distress.detect(text), text


def test_fallback_is_a_question_not_advice():
    """Правило владельца: сначала спросить, что случилось и что нужно."""
    reply = distress.FALLBACK_REPLY
    assert reply.endswith("?")
    assert "что случилось" in reply.lower()
    assert "0800" not in reply and "линия" not in reply.lower()
